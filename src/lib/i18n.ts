export const dict: Record<Lang, Record<string, string>> = { ar, en };

export function t(lang: Lang, key: string): string {
  return dict[lang][key] ?? dict.ar[key] ?? key;
}

export function timeAgo(lang: Lang, iso: string): string {
  const diff = Date.now() - new Date(iso).getTime();
  const mins = Math.max(1, Math.round(diff / 60000));
  if (mins < 60) return lang === "ar" ? `${t(lang, "ago")} ${mins} ${t(lang, "agoMin")}` : `${mins} ${t(lang, "agoMin")} ago`;
  const h = Math.round(mins / 60);
  return lang === "ar" ? `${t(lang, "ago")} ${h} ${t(lang, "agoHour")}` : `${h} ${t(lang, "agoHour")} ago`;
}

export function setDocLang(lang: Lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
}
